#pragma once

/*
 * The fake provider (source-providers.md section 13): every behaviour of the
 * interface, testable without a hypervisor or a container engine.
 *
 *   - Units with BLOB items held in memory, BLOCK items whose content is an
 *     extent map over a seeded generator (so a terabyte disk costs no
 *     memory), and TREE items over real directories.
 *   - Holds that behave like the real ones: a freeze and a pause taken and
 *     released inside begin, a filesystem snapshot and an export held until
 *     end, each journalled through sp_holds_t, and artefacts named with the
 *     daemon's grammar and an ownership proof, so sweep can be shown to
 *     delete exactly its own.
 *   - A failure injectable at every step, including a simulated crash while
 *     holding and a hold that does not come back until the watchdog acts.
 *
 * It is compiled into the daemon so the end-to-end suite can drive units
 * through the API, and enabled only when units.fake_spec names a JSON file
 * of units (fake_provider_load documents the shape). A production config
 * never sets that key.
 */

#include "error.h"
#include "provider.h"

#include <stdint.h>

extern const sp_provider_ops_t fake_provider_ops;

/* Disk content: runs in ascending order; bytes no run covers are reported
 * ZERO and read as zero. */
typedef enum {
    FAKE_RUN_DATA      = 1,  /* generated bytes from seed, reported DATA */
    FAKE_RUN_ZERO_DATA = 2,  /* zero bytes reported DATA (preallocated) */
    FAKE_RUN_ZERO      = 3,  /* reported ZERO, reads as zero */
    FAKE_RUN_FILL      = 4,  /* the byte `seed & 0xff`, reported DATA */
} fake_run_kind_t;

typedef struct {
    uint64_t        off, len;
    fake_run_kind_t kind;
    uint64_t        seed;
} fake_run_t;

/* How the disk's allocation is reported, whatever its content: the extent
 * map a real server would give can differ for the same bytes. */
typedef enum {
    FAKE_ALLOC_EXACT    = 0, /* as the runs say */
    FAKE_ALLOC_ALL_DATA = 1, /* everything DATA (a preallocated image) */
    FAKE_ALLOC_ZERO_AS_ZERO = 2, /* ZERO_DATA runs reported ZERO too */
} fake_alloc_t;

/* The byte the generator puts at off for seed; what a DATA run reads as. */
uint8_t fake_byte(uint64_t seed, uint64_t off);

typedef enum {
    FAKE_FAIL_NONE = 0,
    FAKE_FAIL_DESCRIBE,          /* describe fails */
    FAKE_FAIL_BEGIN,             /* begin fails before taking anything */
    FAKE_FAIL_BEGIN_AFTER_HOLD,  /* begin fails after the freeze: releases itself */
    FAKE_FAIL_BLOB,              /* blob_read fails */
    FAKE_FAIL_BLOCK_OPEN,        /* block_open fails */
    FAKE_FAIL_EXTENT,            /* the extent walk fails */
    FAKE_FAIL_READ,              /* a block read covering byte `arg` fails */
    FAKE_FAIL_TREE_ROOT,         /* tree_root fails */
    FAKE_FAIL_END,               /* end cannot release what it holds */
    FAKE_FAIL_RELEASE,           /* releasing a hold fails, anywhere */
    FAKE_CRASH_IN_HOLD,          /* begin "dies" holding: no release, no clear */
    FAKE_HANG_IN_HOLD,           /* begin holds the freeze up to `arg` ms */
} fake_fail_t;

/* One failure, for one unit id (NULL: every unit). Replaces any set. */
void fake_fail_set(sp_ctx_t *ctx, const char *unit_id, fake_fail_t what, uint64_t arg);
void fake_fail_clear(sp_ctx_t *ctx);

/* Building units. Copies everything. A unit id already present is
 * replaced, which is how a test mutates a unit between sessions. */
status_t fake_unit_add(sp_ctx_t *ctx, const char *unit_id, const char *name,
                       int state, uint32_t caps);
status_t fake_unit_remove(sp_ctx_t *ctx, const char *unit_id);
status_t fake_unit_rename(sp_ctx_t *ctx, const char *unit_id, const char *name);
status_t fake_unit_set_state(sp_ctx_t *ctx, const char *unit_id, int state);
status_t fake_blob_add(sp_ctx_t *ctx, const char *unit_id, const char *item_id,
                       const char *tree_path, const void *data, size_t len);
status_t fake_disk_add(sp_ctx_t *ctx, const char *unit_id, const char *item_id,
                       uint64_t size, const fake_run_t *runs, size_t n_runs,
                       fake_alloc_t alloc);
status_t fake_disk_set_mtime(sp_ctx_t *ctx, const char *unit_id,
                             const char *item_id, int64_t mtime);
status_t fake_tree_add(sp_ctx_t *ctx, const char *unit_id, const char *item_id,
                       const char *read_root, const char *tree_path);

/*
 * Load units from a JSON file, replacing all of them:
 *
 *   {"units":[{"id":"u1","name":"cbk-uat-a","state":"running",
 *              "caps":["quiesce","pause"],
 *              "blobs":[{"id":"domain.xml","path":".cbackup-unit/config/domain.xml",
 *                        "text":"<domain/>"}],
 *              "disks":[{"id":"vda","size":1048576,"alloc":"exact",
 *                        "runs":[{"off":0,"len":65536,"kind":"data","seed":7}]}],
 *              "trees":[{"id":"vol:data","read_root":"/abs/dir",
 *                        "path":"/abs/recorded"}]}]}
 *
 * kind is data, zero_data, zero or fill; alloc is exact, all_data or
 * zero_as_zero. With units.fake_spec set the daemon calls this through
 * init, and again before each enumeration when the file has changed, so
 * a test can mutate units between sessions by rewriting it.
 */
status_t fake_provider_load(sp_ctx_t *ctx, const char *path);

/* What a test asserts on. */
typedef struct {
    unsigned holds_now;        /* freezes, pauses, snapshots, exports held */
    unsigned begins;           /* begin calls that succeeded */
    unsigned begin_failures;
    unsigned ends_committed, ends_aborted;
    unsigned releases;         /* holds released, by anyone */
    unsigned watchdog_released;/* holds a sweep released while begin held them */
    unsigned artefacts;        /* artefacts present, ours and foreign */
} fake_stats_t;
void fake_stats(sp_ctx_t *ctx, fake_stats_t *out);

/*
 * Artefacts the sweep must leave alone. owner is the ownership proof: the
 * fake's equivalent of a ZFS user property or a checkpoint description.
 * NULL owner means the property is absent. job is what the name claims.
 */
status_t fake_artefact_plant(sp_ctx_t *ctx, const char *name, const char *owner);
int      fake_artefact_exists(sp_ctx_t *ctx, const char *name);

/*
 * The data plane, for the helper split (source-providers.md 11.1): the
 * helper holds the unit and the control calls; the daemon reads the bytes
 * itself. For the fake that means the daemon rebuilds a disk's stream from
 * its run map, the way it would read a real export through its own mount.
 */
status_t fake_disk_runs(sp_ctx_t *ctx, const char *unit_id, const char *item_id,
                        uint64_t *size, fake_run_t **runs, size_t *n_runs,
                        fake_alloc_t *alloc);
status_t fake_blob_data(sp_ctx_t *ctx, const char *unit_id, const char *item_id,
                        void **data, size_t *len);
/* A block stream over a run map, owning a copy; close frees it. */
status_t fake_stream_from_runs(uint64_t size, const fake_run_t *runs, size_t n_runs,
                               fake_alloc_t alloc, sp_block_stream_t *out);
/* Units' state, for unit.stop / unit.start behind the helper. */
int      fake_unit_state(sp_ctx_t *ctx, const char *unit_id);

/* A hold as if a previous daemon died holding it: present in the fake's
 * table, released only by a sweep naming it. */
status_t fake_hold_plant(sp_ctx_t *ctx, const char *unit_id, const char *kind,
                         const char *detail);
int      fake_hold_held(sp_ctx_t *ctx, const char *unit_id, const char *kind,
                        const char *detail);
