status_t fake_unit_break_chain(sp_ctx_t *c, const char *unit_id, int lose, int refuse)
{
    pthread_mutex_lock(&c->mu);
    funit_t *u = find_unit(c, unit_id);
    status_t st = u ? OK : set_error(ERR_NOT_FOUND, "fake: no unit %s", unit_id);
    if (st == OK && lose) u->cp[0] = '\0';
    if (st == OK) u->refuse = refuse;
    pthread_mutex_unlock(&c->mu);
    return st;
}

static int job_live(const sp_sweep_req_t *req, int64_t job)
{
    for (size_t i = 0; i < req->n_live_jobs; i++)
        if (req->live_jobs[i] == job) return 1;
    return 0;
}

static status_t f_sweep(sp_ctx_t *c, const sp_sweep_req_t *req, sp_sweep_report_t *out)
{
    memset(out, 0, sizeof(*out));
    pthread_mutex_lock(&c->mu);
    uint64_t arg = 0;
    for (size_t k = 0; k < req->n_intents; k++) {
        const sp_intent_t *in = &req->intents[k];
        fake_fail_t fail = fail_for(c, in->unit_id, &arg);
        int ok = 1, found = 0;
        for (size_t i = 0; i < c->nh; i++) {
            fhold_t *h = &c->holds[i];
            if (!h->held || strcmp(h->unit_id, in->unit_id) != 0 ||
                strcmp(h->kind, in->kind) != 0 || strcmp(h->detail, in->detail) != 0)
                continue;
            found = 1;
            if (hold_release(c, i, fail) != OK) {
                ok = 0;
                if (!out->stuck[0]) snprintf(out->stuck, sizeof(out->stuck), "%.1024s", err_msg());
                err_clear();
            }
            else out->released++;
        }
        /* Nothing held under that name: releasing it is a no-op that
         * succeeds, as thawing a guest that is not frozen does, and is
         * reported as such so the watchdog can tell it from a release. */
        if (!ok) out->failed++;
        if (req->released) req->released[k] = ok;
        if (req->absent) req->absent[k] = !found;
    }
    if (req->scan_artefacts) {
        for (size_t i = 0; i < c->na; i++) {
            fart_t *a = &c->arts[i];
            if (!a->present) continue;
            char d8[9];
            int64_t job = 0;
            if (artefact_parse(a->name, d8, &job, NULL) != 0 ||
                !req->daemon8 || strcmp(d8, req->daemon8) != 0) {
                out->left_foreign++;
                continue;
            }
            if (job_live(req, job)) continue;
            if (!a->has_owner || strcmp(a->owner, req->daemon8) != 0) {
                out->left_foreign++;
                continue;
            }
            /* Ours, leftover, and proven: delete, and with it any hold the
             * table still shows on it. */
            for (size_t h = 0; h < c->nh; h++)
                if (c->holds[h].held && strcmp(c->holds[h].kind, SP_HOLD_FS_SNAPSHOT) == 0 &&
                    strcmp(c->holds[h].detail, a->name) == 0) {
                    c->holds[h].held = 0;
                    c->st.holds_now--;
                    c->st.releases++;
                }
            art_remove(c, a);
            out->removed++;
        }
    }
    pthread_mutex_unlock(&c->mu);
    return OK;
}

/* The unit's spec "probe", the same shape the helper answers; a unit with
 * none answers an empty probe. */
static status_t f_unit_probe(sp_ctx_t *c, const char *unit_id, sp_unit_probe_t **out)
{
    *out = NULL;
    status_t st = maybe_reload(c);
    char *txt = NULL;
    pthread_mutex_lock(&c->mu);
    funit_t *u = st == OK ? find_unit(c, unit_id) : NULL;
    if (st != OK) {
        /* reload failed: said already */
    } else if (!u) {
        st = set_error(ERR_NOT_FOUND, "fake: no unit %s", unit_id);
    } else if (u->probe_fail || fail_for(c, unit_id, NULL) == FAKE_FAIL_PROBE) {
        st = set_error(ERR_IO, "fake: probe of %s failed (injected)", unit_id);
    } else if (u->probe && !(txt = strdup(u->probe))) {
        st = set_error(ERR_NOMEM, "fake: probe");
    }
    pthread_mutex_unlock(&c->mu);
    if (st != OK) return st;
    if (!txt) {
        *out = sp_unit_probe_new();
        return *out ? OK : set_error(ERR_NOMEM, "fake: probe");
    }
    cJSON *o = cJSON_Parse(txt);
    free(txt);
    st = o ? sp_unit_probe_from_json(o, out) : set_error(ERR_INVALID, "fake: probe of %s is not JSON", unit_id);
    cJSON_Delete(o);
    return st;
}

